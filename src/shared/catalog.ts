function buildSeasonalFurniture(
  collection: 'rustica' | 'neon',
  defs: FurnitureDef[]
): CatalogItem[] {
  const meta = SEASON_COLLECTIONS[collection];
  const folder = collection === 'rustica' ? 'rustico' : 'neon';
  const prefix = collection === 'rustica' ? 'rust' : 'neon';
  const filePrefix = collection === 'rustica' ? 'rustico' : 'neon';

  return defs.map(([num, name, shape, rarity, priceCoins, priceGems]) => ({
    id: `${prefix}_${num}`,
    name,
    category: 'movel',
    description: `${meta.name} · Edição limitada por ${meta.durationDays} dias.`,
    priceCoins,
    ...(priceGems ? { priceGems } : {}),
    rarity,
    primaryColor: collection === 'rustica' ? '#92400e' : '#3b0764',
    secondaryColor: collection === 'rustica' ? '#78350f' : '#1e1b4b',
    accentColor: collection === 'rustica' ? '#fbbf24' : '#22d3ee',
    shape,
    tradeable: true,
    spriteUrl: `/assets/furniture/${folder}/${filePrefix}_${num}.png`,
    themeCollection: collection,
    expiresAt: meta.expiresAt,
  }));
}

