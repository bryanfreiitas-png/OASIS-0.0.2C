export function createStarterPlotTiles(): string[] {
  const tiles: string[] = [];
  for (let x = 3; x <= 8; x++) {
    for (let y = 3; y <= 8; y++) {
      tiles.push(`${x},${y}`);
    }
  }
  return tiles;
}

